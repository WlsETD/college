export type PixelIconName = keyof typeof ICONS;

export interface PixelIconProps {
  name: PixelIconName;
  /** 有意義的圖示要給，純裝飾的留空。 */
  label?: string;
  /**
   * 顯示大小。點陣是 16x16，所以只能用 16 的整數倍，
   * 其他尺寸會讓一個點落在非整數的 CSS 像素上而糊掉。
   */
  size?: 16 | 32 | 48;
}

export default function PixelIcon({ name, label, size = 32 }: PixelIconProps) {
  const map = ICONS[name];
  const rects: JSX.Element[] = [];

  map.forEach((row, y) => {
    let runStart: number | null = null;
    for (let x = 0; x <= row.length; x += 1) {
      const on = row[x] === '#';
      if (on && runStart === null) runStart = x;
      if (!on && runStart !== null) {
        rects.push(
          <rect key={`${y}-${runStart}`} x={runStart} y={y} width={x - runStart} height={1} />,
        );
        runStart = null;
      }
    }
  });

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      fill="currentColor"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {label ? <title>{label}</title> : null}
      {rects}
    </svg>
  );
}
